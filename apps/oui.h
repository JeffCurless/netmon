/*
 * oui.h — MAC address vendor lookup (IEEE OUI, a curated subset)
 *
 * The table (apps/oui_data.c) is generated by tools/gen_oui.py and lives in
 * flash.
 */

#ifndef APPS_OUI_H
#define APPS_OUI_H

#include <stdbool.h>
#include <stdint.h>

extern const char *const oui_names[];
extern const uint32_t    oui_table[];
extern const int         oui_table_len;

/* Vendor of a MAC given its first three octets in printed order (the OUI).
 * NULL if the vendor is not in the table.  A locally administered address
 * (bit 1 of the first octet) has no OUI: see oui_is_local(). */
const char *oui_vendor(uint8_t o0, uint8_t o1, uint8_t o2);

/* True for a locally administered address (randomised, or a virtual BSSID). */
static inline bool oui_is_local(uint8_t o0) { return (o0 & 0x02u) != 0u; }

#endif /* APPS_OUI_H */
