def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    pats = [(name, re.compile(rx, re.I)) for name, rx in VENDORS]
    entries = {}
    with open(sys.argv[1], encoding="utf-8", errors="replace") as f:
        for row in csv.reader(f):
            if len(row) < 3 or row[0] != "MA-L":
                continue
            for idx, (_, rx) in enumerate(pats):
                if rx.search(row[2]):
                    entries[int(row[1], 16)] = idx
                    break

    out = sys.stdout
    out.write(LICENSE_HEADER)
    out.write("/* Generated by tools/gen_oui.py from the IEEE OUI registry "
              "(MA-L).  Do not edit. */\n\n")
    out.write('#include "oui.h"\n\n')
    out.write("const char *const oui_names[] = {\n")
    for name, _ in VENDORS:
        out.write(f'    "{name}",\n')
    out.write("};\n\n")
    out.write("/* (OUI << 8) | index into oui_names[], sorted. */\n")
    out.write("const uint32_t oui_table[] = {\n")
    items = sorted(entries.items())
    for i in range(0, len(items), 6):
        chunk = items[i:i + 6]
        out.write("    " + ", ".join(f"0x{o:06X}{v:02X}u" for o, v in chunk)
                  + ",\n")
    out.write("};\n\n")
    out.write("const int oui_table_len = "
              "(int)(sizeof(oui_table) / sizeof(oui_table[0]));\n")
    print(f"{len(items)} OUIs, {len(VENDORS)} vendors", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
