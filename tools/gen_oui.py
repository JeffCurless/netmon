"""
gen_oui.py — build apps/oui_data.c, netmon's MAC vendor table, from the IEEE
OUI registry.

    curl -sSLo oui.csv https://standards-oui.ieee.org/oui/oui.csv
    python3 tools/gen_oui.py oui.csv > apps/oui_data.c

Only the vendors in VENDORS below are kept, to bound the table (it lives in
flash, 4 bytes per OUI).  Each entry is (OUI << 8) | vendor index, sorted, so
oui_vendor() can binary-search it.  Re-run when adding a vendor.
"""

